// Writes the installed @contentauth/c2pa-web version to constants/c2pa-version.ts,
// so the CDN WASM URL always matches the JS that c2pa-web's integrity check expects.
// Runs on `npm install` (root postinstall) and before every common build.
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(resolve(root, 'package.json'))
const { version } = JSON.parse(await readFile(require.resolve('@contentauth/c2pa-web/package.json'), 'utf8'))
const target = resolve(root, 'constants/c2pa-version.ts')
const contents = `// Generated by scripts/c2pa-version.js from the installed @contentauth/c2pa-web. Do not edit.\nexport const C2PA_WEB_VERSION = '${version}'\n`
const current = await readFile(target, 'utf8').catch(() => '')
if(current !== contents) {
	await writeFile(target, contents)
	console.log(`C2PA_WEB_VERSION set to ${version}`)
}
